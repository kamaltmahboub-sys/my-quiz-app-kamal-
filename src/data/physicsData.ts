export function getPartKey(partId: number, subPart = 1): string {
  return `${partId}-${subPart}`;
}

export function getStudyUnitOrder(partId: number, subPart = 1): number {
  let order = 0;
  for (const ch of PHYSICS_PARTS) {
    if (ch.isComprehensive) continue;
    if (ch.subParts && ch.subParts.length > 0) {
      for (const sp of ch.subParts) {
        order++;
        if (ch.id === partId && sp.subPart === subPart) return order;
      }
    } else {
      order++;
      if (ch.id === partId) return order;
    }
  }
  return order;
}

export function getSubPartDetails(partId: number, subPart = 1) {
  const part = PHYSICS_PARTS.find((p) => p.id === partId);
  if (!part) return null;
  const sub = part.subParts?.find((sp) => sp.subPart === subPart) ?? null;
  return {
    part,
    sub,
    lessons: sub ? sub.lessons : (part.lessons ?? []),
    isFirstUnit: getStudyUnitOrder(partId, subPart) <= 1,
  };
}

